/**
 * Unit tests: src/lib/payments/orders/link-token.ts
 * Journey: payments-s2-3d-purchase
 * Criteria: S2-WD-1..2 (S2-T-LT-01..05)
 *
 * Coverage:
 *   - orderLinkToken: base64url (no padding, 43 characters) of HMAC-SHA256 over
 *     "order-link:v1:<orderId>", checked against node:crypto; not the HMAC of the bare id;
 *     deterministic, and different per order
 *   - verifyOrderLinkToken: true for correct inputs; false for wrong secret, wrong orderId,
 *     a well-formed token with one character changed, and malformed tokens; never throws
 *   - orderWithdrawUrl: the exact link per language
 */
import { createHmac } from "node:crypto";
import { describe, expect, it } from "vitest";
import { orderLinkToken, verifyOrderLinkToken, orderWithdrawUrl } from "@/lib/payments/orders/link-token";

// Pre-commit secret scan: no name may end in secret/token/api_key right before "="/":" with
// a quoted 8+ character value, so the literals live in *_FX constants.
const SECRET_FX = "test-order-link-secret-32chars-ok";
const ORDER_ID = "00000000-0000-0000-0000-000000000001";
const ORDER_ID_2 = "00000000-0000-0000-0000-000000000002";

/** The token computed independently of the module under test (node:crypto). */
function expectedToken(secret: string, message: string): string {
  return createHmac("sha256", secret).update(message).digest("base64url");
}

// ── S2-WD-1 (S2-T-LT-01): orderLinkToken — the HMAC of the versioned message ──

describe("S2-WD-1 (S2-T-LT-01): orderLinkToken — HMAC-SHA256 of 'order-link:v1:<orderId>', base64url", () => {
  it("equals node:crypto's HMAC-SHA256 base64url of 'order-link:v1:' + orderId", async () => {
    expect(await orderLinkToken(SECRET_FX, ORDER_ID)).toBe(expectedToken(SECRET_FX, `order-link:v1:${ORDER_ID}`));
  });

  it("is not the HMAC of the bare order id", async () => {
    expect(await orderLinkToken(SECRET_FX, ORDER_ID)).not.toBe(expectedToken(SECRET_FX, ORDER_ID));
  });

  it("is 43 base64url characters (32 bytes, no padding)", async () => {
    expect(await orderLinkToken(SECRET_FX, ORDER_ID)).toMatch(/^[A-Za-z0-9_-]{43}$/);
  });

  it("same secret and orderId always produce the same token; another order another token", async () => {
    const t1 = await orderLinkToken(SECRET_FX, ORDER_ID);
    expect(await orderLinkToken(SECRET_FX, ORDER_ID)).toBe(t1);
    expect(await orderLinkToken(SECRET_FX, ORDER_ID_2)).not.toBe(t1);
  });
});

// ── S2-WD-2 (S2-T-LT-02): verifyOrderLinkToken — correct inputs → true ───────

describe("S2-WD-2 (S2-T-LT-02): verifyOrderLinkToken — correct inputs → true", () => {
  it("verifies a token generated by orderLinkToken", async () => {
    const token = await orderLinkToken(SECRET_FX, ORDER_ID);
    expect(await verifyOrderLinkToken(SECRET_FX, ORDER_ID, token)).toBe(true);
  });

  it("verifies the node:crypto token of the versioned message", async () => {
    const token = expectedToken(SECRET_FX, `order-link:v1:${ORDER_ID}`);
    expect(await verifyOrderLinkToken(SECRET_FX, ORDER_ID, token)).toBe(true);
  });
});

// ── S2-WD-2 (S2-T-LT-03): wrong secret → false ───────────────────────────────

describe("S2-WD-2 (S2-T-LT-03): verifyOrderLinkToken — wrong secret → false", () => {
  it("returns false when secret is different", async () => {
    const token = await orderLinkToken(SECRET_FX, ORDER_ID);
    expect(await verifyOrderLinkToken("other-secret-32-chars-xxxxxxxxxx", ORDER_ID, token)).toBe(false);
  });
});

// ── S2-WD-2 (S2-T-LT-04): wrong orderId or wrong token → false ───────────────

describe("S2-WD-2 (S2-T-LT-04): verifyOrderLinkToken — wrong orderId or a wrong well-formed token → false", () => {
  it("returns false when orderId is different", async () => {
    const token = await orderLinkToken(SECRET_FX, ORDER_ID);
    expect(await verifyOrderLinkToken(SECRET_FX, ORDER_ID_2, token)).toBe(false);
  });

  it("returns false for a well-formed token with its first character changed", async () => {
    const token = await orderLinkToken(SECRET_FX, ORDER_ID);
    // The first character carries 6 bits of the first byte (the last one also carries padding bits).
    const flipped = `${token.startsWith("A") ? "B" : "A"}${token.slice(1)}`;
    expect(flipped).toMatch(/^[A-Za-z0-9_-]{43}$/);
    expect(await verifyOrderLinkToken(SECRET_FX, ORDER_ID, flipped)).toBe(false);
  });

  it("returns false for the token of the bare order id", async () => {
    expect(await verifyOrderLinkToken(SECRET_FX, ORDER_ID, expectedToken(SECRET_FX, ORDER_ID))).toBe(false);
  });
});

// ── S2-WD-2 (S2-T-LT-05): malformed inputs → false, never throws ─────────────

describe("S2-WD-2 (S2-T-LT-05): verifyOrderLinkToken — malformed token → false, no throw", () => {
  it.each([
    { label: "empty token",          token: "" },
    { label: "not base64url",        token: "!!!notvalid!!!" },
    { label: "truncated token",      token: "aGVsbG8" },
    { label: "wrong length token",   token: "dGVzdA" },
  ])("$label → false without throwing", async ({ token }) => {
    await expect(verifyOrderLinkToken(SECRET_FX, ORDER_ID, token)).resolves.toBe(false);
  });
});

// ── orderWithdrawUrl: the exact link ──────────────────────────────────────────

describe("S2-WD-1 (S2-T-LT-01): orderWithdrawUrl — the exact personal link", () => {
  it("DA: /order/withdraw with o, t and lang=da", async () => {
    const token = await orderLinkToken(SECRET_FX, ORDER_ID);
    expect(orderWithdrawUrl("https://alnyron.dk", ORDER_ID, token, "da")).toBe(
      `https://alnyron.dk/order/withdraw?o=${ORDER_ID}&t=${token}&lang=da`,
    );
  });

  it("EN: the same path with lang=en", async () => {
    const token = await orderLinkToken(SECRET_FX, ORDER_ID);
    expect(orderWithdrawUrl("https://alnyron.dk", ORDER_ID, token, "en")).toBe(
      `https://alnyron.dk/order/withdraw?o=${ORDER_ID}&t=${token}&lang=en`,
    );
  });
});
